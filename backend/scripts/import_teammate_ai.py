BACKEND_ROOT = Path(__file__).resolve().parents[1]

SOURCE_ZIP = (
    Path("/home/niggatron/Downloads")
    / "SIH26_Aurora_compatible.zip"
)

AI_ROOT = BACKEND_ROOT / "ai"
